"""llama-swap connector.

GPU Shepherd owns llama-swap's config file: it is rendered from the model catalogue that you
edit in the UI (catalogs/<id>.yaml) every time the container is (re)created. The container
only sees the GPUs it was given, so no CUDA_VISIBLE_DEVICES juggling is needed.

"Auto aliases" are model names that resolve to different models depending on how many GPUs
the server currently has - e.g. "coder" = a big MoE model with 2 GPUs, a smaller one with 1.
"""
from __future__ import annotations

import json
import shlex
import time
from pathlib import Path

import httpx
import yaml

from ..config import Catalog, Instance
from . import instance_url

CONTAINER_PORT = 8080
CONFIG_PATHS = ("/app/config.yaml", "/etc/llama-swap/config/config.yaml")   # older and newer images
API_KEY_ENV = "LLAMA_SWAP_API_KEY"
DETECT_SCRIPT = ("command -v llama-server || { [ -x /app/llama-server ] && echo /app/llama-server; } "
                 "|| find / -name llama-server -type f 2>/dev/null | head -n 1")


def render(catalog: Catalog, gpu_count: int, threads: int) -> str:
    server = catalog.llama_server or "/app/llama-server"
    auto_for: dict[str, list[str]] = {}
    for auto in catalog.auto_aliases:
        auto_for.setdefault(auto.resolve(gpu_count), []).append(auto.alias)

    models = {}
    for m in catalog.models:
        args = [shlex.quote(server), "--host", "127.0.0.1", "--port", "${PORT}", "--jinja",
                "--threads", str(threads), "--model", shlex.quote(m.file),
                "--ctx-size", str(m.ctx_size), "--parallel", str(m.parallel)]
        if m.kv_cache != "f16":
            args += ["--cache-type-k", m.kv_cache, "--cache-type-v", m.kv_cache]
        if m.mmproj:
            args += ["--mmproj", shlex.quote(m.mmproj), "--no-mmproj-offload"]
        if m.role == "embed":
            args.append("--embeddings")
        elif m.role == "rerank":
            args.append("--reranking")
        if m.thinking != "auto" and m.role == "chat":
            kwargs = json.dumps({"enable_thinking": m.thinking == "on"})
            args += ["--chat-template-kwargs", shlex.quote(kwargs)]
        if m.mtp and m.role == "chat":
            if m.mtp_draft:
                args += ["--model-draft", shlex.quote(m.mtp_draft)]
            args += ["--spec-type", "draft-mtp", "--spec-draft-n-max", str(m.mtp)]
        if gpu_count > 1 and m.split_mode != "layer":
            args += ["--split-mode", m.split_mode]
        if gpu_count > 1 and m.tensor_split:
            shares = m.tensor_split.split(",")
            if len(shares) >= gpu_count:     # one share per GPU it has now; the first ones when it has fewer
                args += ["--tensor-split", ",".join(shares[:gpu_count])]
        rule = m.offload_for(gpu_count)
        if rule and rule.gpu_layers is not None:
            args += ["--n-gpu-layers", str(rule.gpu_layers)]
        if rule and rule.cpu_moe:
            args += ["--n-cpu-moe", str(rule.cpu_moe)]
        if m.sampling:
            args.append(m.sampling)
        if m.extra_args:
            args.append(m.extra_args)
        entry: dict = {"name": m.name or m.id, "cmd": " ".join(args)}
        if m.description:
            entry["description"] = m.description
        aliases = list(m.aliases) + auto_for.get(m.id, [])
        if aliases:
            entry["aliases"] = aliases
        if m.ttl:
            entry["ttl"] = m.ttl
        models[m.id] = entry

    cfg = {
        "healthCheckTimeout": catalog.health_timeout,
        "logLevel": "info",
        "sendLoadingState": True,
        "globalTTL": 0,
        "apiKeys": ["${env.%s}" % API_KEY_ENV],
        "models": models,
    }
    # Models are swapped one at a time; a model kept loaded (an embedding model) sits in its own
    # group beside them, which loading another model never unloads.
    kept = [m.id for m in catalog.models if m.keep_loaded]
    if kept:
        cfg["groups"] = {
            "models": {"swap": True, "exclusive": False,
                       "members": [m.id for m in catalog.models if not m.keep_loaded]},
            "kept-loaded": {"swap": False, "exclusive": False, "persistent": True, "members": kept},
        }
        if not cfg["groups"]["models"]["members"]:
            del cfg["groups"]["models"]
    preload = [m.id for m in catalog.models if m.preload]
    if preload:
        cfg["hooks"] = {"on_startup": {"preload": preload}}
    header = (f"# Generated by GPU Shepherd from catalogs/{catalog.instance_id}.yaml for {gpu_count} GPU(s).\n"
              "# Do not edit: it is rewritten whenever the instance starts. Edit the catalogue in the UI.\n")
    return header + yaml.safe_dump(cfg, sort_keys=False, width=4000, allow_unicode=True)


def resolved_aliases(catalog: Catalog, gpu_count: int) -> dict[str, str]:
    return {a.alias: a.resolve(gpu_count) for a in catalog.auto_aliases}


def local_model_files(inst: Instance, limit: int = 300) -> tuple[list[dict], list[str]]:
    """.gguf files in the instance's volumes that GPU Shepherd can see (mounted at the same path).
    Returns ([{container_path, size_gb}], notes)."""
    files, notes = [], []
    for vol in inst.volumes:
        host = Path(vol.host)
        if not host.is_dir():
            notes.append(f"{vol.host} is not visible to GPU Shepherd - mount it into its container at the "
                         "same path to browse the model files there.")
            continue
        for path in sorted(host.rglob("*.gguf")):
            rel = path.relative_to(host)
            if len(rel.parts) > 4:
                continue
            try:
                size = path.stat().st_size / 1_073_741_824
            except OSError:
                continue
            files.append({"container_path": str(Path(vol.container) / rel), "size_gb": round(size, 1),
                          "name": path.name})
            if len(files) >= limit:
                return files, notes
    return files, notes


class LlamaSwapClient:
    def __init__(self, base_url: str, api_key: str, timeout: float = 5.0):
        self.base = base_url.rstrip("/")
        self.headers = {"Authorization": f"Bearer {api_key}"}
        self.timeout = timeout

    def _get(self, path: str):
        r = httpx.get(self.base + path, headers=self.headers, timeout=self.timeout)
        r.raise_for_status()
        return r.json()

    def models(self) -> list[dict]:
        return [m for m in self._get("/v1/models").get("data", []) if m.get("id")]

    def running(self, known: set[str]) -> dict[str, str]:
        """Model id -> state for loaded models. llama-swap's /running format is not documented,
        so walk whatever JSON comes back and pick out known model ids."""
        try:
            data = self._get("/running")
        except (httpx.HTTPError, ValueError):
            return {}
        found: dict[str, str] = {}

        def walk(node):
            if isinstance(node, dict):
                mid = node.get("model") or node.get("id") or node.get("name")
                if isinstance(mid, str) and mid in known:
                    found[mid] = str(node.get("state", "ready"))
                for v in node.values():
                    walk(v)
            elif isinstance(node, list):
                for v in node:
                    walk(v)
        walk(data)
        return found

    def in_flight(self, known: set[str], wait: float = 3.0) -> tuple[int, dict[str, int]] | None:
        """Requests llama-swap is still answering: (total, per model), or None if it can't say.

        Newer llama-swap sends a snapshot of its in-flight requests as soon as /api/events is
        opened. Older ones don't, so then ask llama-server's /slots of each loaded model."""
        found = self._events_in_flight(wait)
        if found is None:
            found = self._slots_in_flight(known)
        if found is None:
            return None
        return sum(found.values()), found

    def _events_in_flight(self, wait: float) -> dict[str, int] | None:
        deadline = time.monotonic() + wait
        try:
            with httpx.stream("GET", self.base + "/api/events", headers=self.headers,
                              timeout=httpx.Timeout(wait, connect=self.timeout)) as r:
                if r.status_code >= 400:
                    return None
                for line in r.iter_lines():
                    if line.startswith("data:"):
                        msg = json.loads(line[5:])
                        if isinstance(msg, dict) and msg.get("type") == "inflight":
                            return _count_in_flight(json.loads(msg.get("data") or "{}"))
                    if time.monotonic() > deadline:
                        break
        except (httpx.HTTPError, ValueError):
            pass
        return None

    def _slots_in_flight(self, known: set[str]) -> dict[str, int] | None:
        found = {}
        for mid, state in self.running(known).items():
            if state != "ready":
                continue
            try:
                busy = busy_slots(self._get(f"/upstream/{mid}/slots"))
            except (httpx.HTTPError, ValueError, TypeError):
                return None
            if busy:
                found[mid] = busy
        return found

    def load(self, model: str, timeout: float = 1800) -> None:
        """llama-swap has no documented 'load' call; a 1-token request loads the model."""
        r = httpx.post(self.base + "/v1/chat/completions", headers=self.headers, timeout=timeout,
                       json={"model": model, "max_tokens": 1, "messages": [{"role": "user", "content": "hi"}]})
        r.raise_for_status()

    def unload(self, model: str | None = None) -> None:
        attempts = []
        if model:
            attempts.append(("POST", f"/api/models/unload/{model}"))
        attempts += [("POST", "/api/models/unload"), ("GET", "/unload"), ("POST", "/unload")]
        last = None
        for method, path in attempts:
            try:
                r = httpx.request(method, self.base + path, headers=self.headers, timeout=60)
                if r.status_code < 400:
                    return
                last = f"HTTP {r.status_code}"
            except httpx.HTTPError as err:
                last = str(err)
        raise RuntimeError(f"unload failed ({last})")


def _count_in_flight(data) -> dict[str, int]:
    """Per-model counts from llama-swap's in-flight snapshot ({"requests": [{"model": ...}]})."""
    found: dict[str, int] = {}
    if isinstance(data, dict) and isinstance(data.get("requests"), list):
        for req in data["requests"]:
            mid = str(req.get("model") or "?") if isinstance(req, dict) else "?"
            found[mid] = found.get(mid, 0) + 1
    elif isinstance(data, dict) and isinstance(data.get("total"), int) and data["total"] > 0:
        found["?"] = data["total"]
    return found


def busy_slots(slots) -> int:
    """How many llama-server slots are working (is_processing in new builds, state 1 in old ones)."""
    if not isinstance(slots, list):
        raise TypeError("unexpected /slots answer")
    return sum(1 for s in slots if isinstance(s, dict) and (s.get("is_processing") or s.get("state", 0) != 0))


def client_for(inst: Instance, catalog: Catalog) -> LlamaSwapClient:
    return LlamaSwapClient(instance_url(inst, CONTAINER_PORT), catalog.api_key)


def pretty(catalog_text: str) -> str:
    """Re-indent a rendered config for display."""
    try:
        return json.dumps(yaml.safe_load(catalog_text), indent=2)
    except yaml.YAMLError:
        return catalog_text
